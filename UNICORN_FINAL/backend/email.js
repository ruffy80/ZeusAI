/**
 * Email service – wraps nodemailer with a simple helper.
 * Falls back to console logging when SMTP credentials are not configured.
 */

'use strict';

const nodemailer = require('nodemailer');

// Citire dinamică (lazy) – nu se cachează la load time, ci la primul apel.
// Astfel quantumVault poate injecta secretele în process.env înainte de primul email.
function getSmtpConfig() {
  return {
    host:     process.env.SMTP_HOST     || '',
    port:     parseInt(process.env.SMTP_PORT || '587', 10),
    user:     process.env.SMTP_USER     || '',
    pass:     process.env.SMTP_PASS     || '',
    fromName: process.env.EMAIL_FROM_NAME || 'Zeus AI',
    fromEmail: process.env.SMTP_USER || process.env.ADMIN_EMAIL || 'noreply@zeusai.pro',
    appUrl:   process.env.PUBLIC_APP_URL || 'https://zeusai.pro',
  };
}

function smtpIsConfigured() {
  const cfg = getSmtpConfig();
  return Boolean(cfg.host && cfg.user && cfg.pass);
}

// Lazy-loaded HTTPS transactional provider bridge (Resend / Brevo / Sendinblue /
// MailerSend). Kept optional so backend/email.js still works if the file is
// missing (e.g. bootstrap or partial checkout). Return values follow the
// { ok, provider, reason, error } contract exported by src/commerce/transactional-email.
function _httpsMailer() {
  try { return require('../src/commerce/transactional-email'); }
  catch (_) { return null; }
}
function httpsIsConfigured() {
  const m = _httpsMailer();
  return !!(m && typeof m.configuredProviders === 'function' && m.configuredProviders().length > 0);
}
function isConfigured() {
  return httpsIsConfigured() || smtpIsConfigured();
}

let _transporter = null;
let _transporterConfig = null;
function getTransporter() {
  const cfg = getSmtpConfig();
  // Recreate transporter if config changed (e.g. after vault inject)
  const cfgKey = `${cfg.host}:${cfg.port}:${cfg.user}`;
  if (!_transporter || _transporterConfig !== cfgKey) {
    _transporter = nodemailer.createTransport({
      host:   cfg.host,
      port:   cfg.port,
      secure: cfg.port === 465,
      auth:   { user: cfg.user, pass: cfg.pass },
    });
    _transporterConfig = cfgKey;
  }
  return _transporter;
}

// Persistent JSONL outbox for messages queued while SMTP credentials are
// unavailable. The outbox is replayed by the SMTP transport once configured
// (see ai-sdr-agent / scripts/smtp-replay), so no notification is ever lost.
const _path  = require('path');
const _fs    = require('fs');
const OUTBOX_DIR  = _path.join(__dirname, '..', 'data', 'outbox');
const OUTBOX_FILE = _path.join(OUTBOX_DIR, 'email.jsonl');

function _persistOutbox(entry) {
  try {
    _fs.mkdirSync(OUTBOX_DIR, { recursive: true });
    _fs.appendFileSync(OUTBOX_FILE, JSON.stringify(entry) + '\n', 'utf8');
    return true;
  } catch (e) {
    console.warn('[email] outbox persist failed:', e && e.message);
    return false;
  }
}

async function sendMail({ to, subject, html, text }) {
  const startedAt = Date.now();

  // 1. Prefer HTTPS transactional providers (Resend/Brevo/Sendinblue/MailerSend).
  //    On Hetzner outbound SMTP is frequently firewalled; HTTPS providers work
  //    out of the box with just an API key and land in the recipient inbox.
  //    We route through the shared src/commerce/transactional-email.js so that
  //    provider order, retries and headers stay consistent site-wide.
  if (httpsIsConfigured()) {
    const m = _httpsMailer();
    try {
      const r = await m.sendRaw({ to, subject, text, html });
      if (r && r.ok) {
        console.log(`[email] sent via ${r.provider} to=${to} messageId=${r.messageId || 'n/a'} latencyMs=${Date.now() - startedAt}`);
        return { ok: true, provider: r.provider, messageId: r.messageId || null, latencyMs: Date.now() - startedAt };
      }
      // HTTPS provider present but the send failed — fall through to SMTP if
      // configured, otherwise persist to outbox with the underlying error.
      console.warn(`[email] https provider send failed to=${to} err=${(r && r.error) || 'unknown'}`);
    } catch (e) {
      console.warn(`[email] https provider threw to=${to} err=${e && e.message}`);
    }
  }

  // 2. Fallback: SMTP via nodemailer (traditional path).
  if (smtpIsConfigured()) {
    const cfg = getSmtpConfig();
    try {
      const info = await getTransporter().sendMail({
        from: `"${cfg.fromName}" <${cfg.fromEmail}>`,
        to, subject, html, text,
      });
      console.log(`[email] sent via smtp to=${to} messageId=${info.messageId} latencyMs=${Date.now() - startedAt}`);
      return info;
    } catch (err) {
      _persistOutbox({
        at: new Date().toISOString(),
        to, subject, html, text,
        reason: 'smtp_send_failed',
        error: err && err.message,
      });
      console.error(`[email] smtp send failed -> queued to=${to} err=${err && err.message}`);
      throw err;
    }
  }

  // 3. No transport configured — persist to outbox and return a fail-honest
  //    result. We keep `queued:true` so the smtp-replay job can still ship
  //    it later, but ok:false + reason surface the current state to callers
  //    that actually check the return value.
  const queued = _persistOutbox({
    at: new Date().toISOString(),
    to, subject, html, text,
    reason: 'email_unconfigured',
  });
  console.log(`[email] queued -> outbox to=${to} subject="${subject}" persisted=${queued}`);
  return { ok: false, queued: true, persisted: queued, outbox: OUTBOX_FILE, reason: 'email_unconfigured' };
}

/**
 * Replay queued outbox messages once a transport is configured.
 * Marks successfully sent lines by rewriting the JSONL without them.
 */
async function replayOutbox({ limit = 25 } = {}) {
  if (!isConfigured()) {
    return { ok: false, reason: 'email_unconfigured', replayed: 0, remaining: 0 };
  }
  let lines = [];
  try {
    if (!_fs.existsSync(OUTBOX_FILE)) return { ok: true, replayed: 0, remaining: 0 };
    lines = _fs.readFileSync(OUTBOX_FILE, 'utf8').split(/\n/).filter(Boolean);
  } catch (e) {
    return { ok: false, error: e.message, replayed: 0 };
  }
  const keep = [];
  let replayed = 0;
  for (let i = 0; i < lines.length; i++) {
    let entry;
    try { entry = JSON.parse(lines[i]); } catch (_) { continue; }
    if (replayed >= limit) { keep.push(lines[i]); continue; }
    try {
      const r = await sendMail({
        to: entry.to,
        subject: entry.subject,
        html: entry.html,
        text: entry.text,
      });
      if (r && (r.ok === true || r.messageId)) {
        replayed += 1;
      } else {
        keep.push(lines[i]);
      }
    } catch (_) {
      keep.push(lines[i]);
    }
  }
  try {
    _fs.mkdirSync(OUTBOX_DIR, { recursive: true });
    _fs.writeFileSync(OUTBOX_FILE, keep.length ? keep.join('\n') + '\n' : '', 'utf8');
  } catch (e) {
    return { ok: false, error: e.message, replayed, remaining: keep.length };
  }
  return { ok: true, replayed, remaining: keep.length };
}

let _replayTimer = null;
function startOutboxReplay(intervalMs) {
  const ms = Math.max(60_000, Number(intervalMs || process.env.EMAIL_OUTBOX_REPLAY_MS || 10 * 60 * 1000) || 600_000);
  if (_replayTimer) return { ok: true, already: true, intervalMs: ms };
  _replayTimer = setInterval(() => {
    replayOutbox().catch((e) => console.warn('[email] outbox replay failed:', e && e.message));
  }, ms);
  if (typeof _replayTimer.unref === 'function') _replayTimer.unref();
  if (isConfigured()) {
    replayOutbox().catch(() => {});
  }
  return { ok: true, intervalMs: ms };
}

function stopOutboxReplay() {
  if (_replayTimer) { clearInterval(_replayTimer); _replayTimer = null; }
}

