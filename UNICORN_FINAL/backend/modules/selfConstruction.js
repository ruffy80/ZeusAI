const fs = require('fs');
const path = require('path');

// =====================================================================
// SelfConstruction — Auditor & Builder SIGUR pentru întreg Unicornul.
//
// Versiunea veche suprascria orice fișier sub 200 de caractere cu un stub
// generic — comportament DISTRUCTIV care putea corupe module reale. A fost
// înlocuit complet. Noul motor / The new engine:
//   • scan()  — parcurge recursiv backend/modules și detectează module goale,
//               fără module.exports, cu marcaje placeholder/stub/TODO, sau cu
//               anteturi OWNERSHIP duplicate.
//   • audit() — raport structurat, READ-ONLY (sigur în profil 'safe').
//   • start({ apply }) — implicit READ-ONLY. Doar cu apply:true ȘI cu
//               file-mutators activate completează module GENUIN goale/lipsă
//               cu un schelet funcțional. NU suprascrie niciodată cod real.
// Compatibil cu rutele existente (hasRun, start()).
// =====================================================================

const SKIP_DIRS = new Set(['node_modules', 'autoGenerated', '.git']);
const PLACEHOLDER_RX = /\b(placeholder|not implemented|notImplemented|coming soon|TODO|FIXME|\[stub|mock-tx-)/i;
const OWNERSHIP_RX = /OWNERSHIP: Acest fișier/g;

function _walk(dir, out) {
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch (_) { return out; }
  for (const e of entries) {
    if (SKIP_DIRS.has(e.name)) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) _walk(full, out);
    else if (e.name.endsWith('.js')) out.push(full);
  }
  return out;
}

function _classify(file) {
  let content = '';
  try { content = fs.readFileSync(file, 'utf8'); } catch (_) { return { file, unreadable: true }; }
  const codeOnly = content.replace(/OWNERSHIP[\s\S]*?===\n/g, '');
  const ownershipHeaders = (content.match(OWNERSHIP_RX) || []).length;
  const trimmed = content.trim();
  return {
    file,
    bytes: content.length,
    empty: trimmed.length === 0,
    noExports: !/module\.exports/.test(content) && !/export\s+(default|const|function|class)/.test(content),
    placeholder: PLACEHOLDER_RX.test(codeOnly),
    duplicateOwnership: ownershipHeaders > 1,
    ownershipHeaders,
  };
}

// Singleton ca obiect simplu (FĂRĂ `class`/`constructor()` și fără class
// fields): astfel runtime code-enhancers care injectează după `constructor()`
// nu pot corupe acest fișier, iar ESLint-ul proiectului nu se plânge de
// sintaxă. NU transforma înapoi în class cu constructor().
const selfConstruction = {
  hasRun: false,
  lastReport: null,
  modulesDir: path.join(__dirname),

  scan() {
    const files = _walk(this.modulesDir, []);
    const findings = files.map(_classify);
    return {
      total: files.length,
      empty: findings.filter(f => f.empty).map(f => path.relative(this.modulesDir, f.file)),
      noExports: findings.filter(f => f.noExports && !f.empty).map(f => path.relative(this.modulesDir, f.file)),
      placeholders: findings.filter(f => f.placeholder).map(f => path.relative(this.modulesDir, f.file)),
      duplicateOwnership: findings.filter(f => f.duplicateOwnership)
        .map(f => ({ file: path.relative(this.modulesDir, f.file), headers: f.ownershipHeaders })),
    };
  },

  audit() {
    const scan = this.scan();
    const report = {
      generatedAt: new Date().toISOString(),
      mode: 'read-only-audit',
      totals: {
        modules: scan.total,
        empty: scan.empty.length,
        noExports: scan.noExports.length,
        placeholders: scan.placeholders.length,
        duplicateOwnership: scan.duplicateOwnership.length,
      },
      details: scan,
    };
    this.lastReport = report;
    return report;
  },

  // Schelet funcțional pentru module GENUIN goale/fără export (nu cod real).
  _buildSkeleton(name) {
    return [
      '// ' + name + ' — auto-completed working module (SelfConstruction).',
      'let _state = { calls: 0, lastRun: null, createdAt: new Date().toISOString() };',
      '',
      'module.exports = {',
      "  name: '" + name + "',",
      '  isActive: true,',
      '  async process(input = {}) {',
      '    _state.calls++; _state.lastRun = new Date().toISOString();',
      "    return { ok: true, module: '" + name + "', calls: _state.calls, input };",
      '  },',
      '  getStatus() {',
      "    return { name: '" + name + "', status: 'active', calls: _state.calls, lastRun: _state.lastRun, createdAt: _state.createdAt };",
      '  },',
      '};',
      '',
    ].join('\n');
  },

  // ── Autonomy surface (getStatus/process) ──────────────────────────────────
  // READ-ONLY. process() NEVER applies skeletons — it only runs the audit so
  // the standalone PM2 runner can heartbeat safely (apply:false semantics).
  getStatus() {
    // Prefer lastReport when fresh (<10 min) — recursive module walk on every
    // IAK/ops status poll was a major event-loop lag contributor.
    const FRESH_MS = 10 * 60 * 1000;
    let totals = null;
    try {
      const lr = this.lastReport;
      const lrAt = lr && lr.generatedAt ? Date.parse(lr.generatedAt) : 0;
      if (lr && lr.totals && lrAt && (Date.now() - lrAt) < FRESH_MS) {
        totals = lr.totals;
      } else {
        const scan = this.scan();
        totals = {
          modules: scan.total,
          empty: scan.empty.length,
          noExports: scan.noExports.length,
          placeholders: scan.placeholders.length,
          duplicateOwnership: scan.duplicateOwnership.length,
        };
      }
    } catch (_) { totals = null; }
    return {
      module: 'selfConstruction',
      name: 'Self-Construction (read-only audit)',
      status: 'active',
      mode: 'read-only-audit',
      hasRun: this.hasRun,
      totals,
      lastReportAt: this.lastReport && this.lastReport.generatedAt ? this.lastReport.generatedAt : null,
      updatedAt: new Date().toISOString(),
    };
  },

  async process(input = {}) {
    const action = (input && input.action) || 'tick';
    switch (action) {
      case 'tick':
      case 'audit': {
        const report = this.audit();
        this.hasRun = true;
        return { ok: true, action: 'audit', applied: false, report };
      }
      case 'status':
        return this.getStatus();
      default:
        return { ok: false, error: `unknown action: ${action}`, supported: ['tick', 'audit', 'status'] };
    }
  },

  async start(opts = {}) {
    // ── Hard mutator gate (fail-closed) ──────────────────────────────────
    // Refuse to ever write files when self-mutation is disabled OR the
    // explicit file-mutator opt-in is not set. This runs BEFORE any audit or
    // writeFileSync so no source file can be overwritten in dev/CI/prod-stable.
    // Audit/tick (process()) stay read-only and are unaffected.
    if (process.env.DISABLE_SELF_MUTATION === '1') {
      return { applied: false, refused: true, reason: 'DISABLE_SELF_MUTATION=1' };
    }
    if (!['1', 'true', 'yes', 'on'].includes(String(process.env.ENABLE_FILE_MUTATORS || '').toLowerCase())) {
      return { applied: false, refused: true, reason: 'ENABLE_FILE_MUTATORS not set' };
    }
    const apply = opts.apply === true || process.env.SELF_CONSTRUCTION_APPLY === '1';
    const report = this.audit();
    this.hasRun = true;

    if (!apply) {
      console.log('🧱 Self‑Construction: audit READ-ONLY — ' +
        report.totals.placeholders + ' placeholder, ' +
        report.totals.empty + ' goale, ' +
        report.totals.noExports + ' fără export.');
      return { applied: false, report };
    }

    // Mod APLICARE: doar module goale / fără export primesc schelet funcțional.
    const toBuild = [...report.details.empty, ...report.details.noExports];
    const built = [];
    for (const rel of toBuild) {
      const full = path.join(this.modulesDir, rel);
      try {
        const name = path.basename(rel, '.js');
        fs.writeFileSync(full, this._buildSkeleton(name));
        built.push(rel);
      } catch (e) {
        console.error('[self-construction] nu am putut completa', rel, e.message);
      }
    }
    console.log('🛠️ Self‑Construction: ' + built.length + ' module completate (apply).');
    return { applied: true, built, report };
  },
};

// Essential-module contract aliases
selfConstruction.scanAllModules = function scanAllModules() {
  return this.audit();
};
selfConstruction.enhanceModule = function enhanceModule(name) {
  return { ok: true, module: name, enhanced: false, note: 'use start({apply:true}) under ENABLE_FILE_MUTATORS=1' };
};
selfConstruction.createMissingModules = async function createMissingModules() {
  if (String(process.env.ENABLE_FILE_MUTATORS || '') !== '1') {
    return { ok: true, created: 0, gated: true };
  }
  return this.start({ apply: true });
};

module.exports = selfConstruction;
