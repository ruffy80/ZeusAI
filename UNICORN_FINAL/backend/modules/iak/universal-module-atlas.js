'use strict';

const fs = require('fs');
const path = require('path');

const PROTOCOL = 'UMAS/1.0';
const APP_ROOT = path.resolve(__dirname, '..', '..', '..');
const CACHE_TTL_MS = 60 * 1000;
const SKIP_DIRS = new Set(['node_modules', 'autoGenerated', '.git', 'dist', 'build', 'coverage']);

let _cache = null;
let _cacheAt = 0;

function walkJsFiles(rootDir, relPrefix, out) {
  let entries = [];
  try {
    entries = fs.readdirSync(rootDir, { withFileTypes: true });
  } catch (_) {
    return out;
  }
  for (const ent of entries) {
    if (SKIP_DIRS.has(ent.name)) continue;
    const abs = path.join(rootDir, ent.name);
    const rel = relPrefix ? `${relPrefix}/${ent.name}` : ent.name;
    if (ent.isDirectory()) {
      walkJsFiles(abs, rel, out);
    } else if (ent.isFile() && ent.name.endsWith('.js')) {
      out.push({ abs, rel });
    }
  }
  return out;
}

function classifyOrgan(relPath, surface) {
  const s = String(relPath || '').toLowerCase();
  if (/(security|auth|crypto|shield|guard|fraud|witness|immunit|audit|honeypot|compliance|privacy|quarantine|ed25519|trust|integrity|pq|quantum-security|anti-)/.test(s)) {
    return 'redteam_security';
  }
  if (/(checkout|commerce|pric|upsell|bundle|negotiat|revenue|profit|money|m2m|x402|pay|billing|stripe|paypal|btc|treasury|wallet|order|invoice|wealth|monetiz|affiliate|referral|margin|tax|ledger|deal|catalog|shelf|sales)/.test(s)) {
    return 'cro_conversion';
  }
  if (/(seo|aeo|geo|viral|social|traffic|market|outreach|magnet|world-index|sitemap|indexnow|growth|content|blog|email|newsletter|telegram|discord|twitter|facebook|instagram|share|relay|gravity|funnel|lead|sdr|acquisition)/.test(s)) {
    return 'growth_acquisition';
  }
  if (/(fulfill|deliver|provision|aspe|zacc|dropship|client|service|workflow|agent|chatbot|concierge|llm|swarm|ollama|groq|openrouter|connector|mcp|a2a|ai-|prompt|rag|voice|vision|video|design|portal|customer|vertical|industry)/.test(s)) {
    return 'fulfillment_quality';
  }
  if (/(health|heal|watchdog|monitor|memory|perf|cache|slo|chaos|failover|recovery|backup|immortal|resilien|circuit|proxy|phoenix|uptime|latency|doctor|reaper|guardian|load|cluster|edge|metrics|telemetry|log|sla)/.test(s)) {
    return 'sre_performance';
  }
  if (/(evolv|evolution|genome|learn|innovat|50y|100y|30y|agi|research|singularity|continuum|kernel|orchestrat|iak|clockwork|synaptic|organism|autonom|brain|cortex|spine|self-|meta|quantum)/.test(s)) {
    return 'git_native_evolution';
  }
  if (surface === 'src/commerce') return 'cro_conversion';
  if (surface === 'src/security') return 'redteam_security';
  if (surface === 'src/seo') return 'growth_acquisition';
  if (surface === 'src/perf' || surface === 'src/monitoring') return 'sre_performance';
  if (surface === 'src/innovation') return 'git_native_evolution';
  return 'core_infrastructure';
}

function readIakLiveSummary() {
  try {
    // Only inspect if IAK is already loaded in require.cache (never boot IAK as a side effect)
    const iakPath = require.resolve('../integrated-autonomy-kernel');
    const cached = require.cache[iakPath];
    if (cached && cached.exports && typeof cached.exports.getStatus === 'function') {
      const st = cached.exports.getStatus();
      if (st && typeof st.totalModules === 'number') {
        return {
          loaded: true,
          running: !!st.running,
          mode: st.mode || null,
          totalModules: st.totalModules,
          healthyModules: st.healthyModules,
          unhealthyCount: st.unhealthyCount || 0,
          quarantined: st.quarantined || 0,
          meshHealthy: st.meshHealthy !== false,
        };
      }
    }
  } catch (_) {}
  return {
    loaded: false,
    running: false,
    mode: null,
    totalModules: 0,
    healthyModules: 0,
    unhealthyCount: 0,
    quarantined: 0,
    meshHealthy: null,
  };
}

function buildAtlas() {
  const now = Date.now();
  if (_cache && (now - _cacheAt) < CACHE_TTL_MS) return _cache;

  const entries = [];
  const manifestMap = new Map();

  // 1. Discover all manifest modules (currently 30)
  try {
    const { discoverModules } = require('../orchestrator/discovery');
    const discovered = discoverModules([path.join(APP_ROOT, 'backend', 'modules')]);
    for (const m of discovered) {
      manifestMap.set(m.name, {
        name: m.name,
        version: m.version || '1.0.0',
        capabilitiesCount: Array.isArray(m.capabilities) ? m.capabilities.length : 0,
        dependenciesCount: Array.isArray(m.dependencies) ? m.dependencies.length : 0,
      });
    }
  } catch (_) {}

  // 2. Reuse MCOV/1.0 static sheet for ALL backend/modules/**/*.js (~751 files)
  let mcovSummary = {
    files: 0,
    runtime: 0,
    libraries: 0,
    aliases: 0,
    nested: 0,
    brokenAliases: 0,
  };
  try {
    const mcov = require('./module-coverage');
    const sh = mcov.sheet();
    let rt = 0;
    let lib = 0;
    let ali = 0;
    let nes = 0;
    let broken = 0;
    for (const e of (sh.entries || [])) {
      if (e.nested) nes += 1;
      if (e.kind === 'runtime') rt += 1;
      else if (e.kind === 'alias') {
        ali += 1;
        if (e.aliasOk === false) broken += 1;
      } else lib += 1;

      const topFolder = e.file.includes('/') ? e.file.split('/')[0] : null;
      const manifestMeta = (topFolder && manifestMap.get(topFolder)) || manifestMap.get(e.name) || null;
      entries.push({
        id: 'backend/modules/' + e.file,
        name: e.name,
        surface: 'backend/modules',
        kind: e.kind,
        signal: e.signal || null,
        hasManifest: Boolean(manifestMeta),
        manifestName: manifestMeta ? manifestMeta.name : null,
        organ: classifyOrgan(e.file, 'backend/modules'),
      });
    }
    mcovSummary = {
      files: (sh.entries || []).length,
      runtime: rt,
      libraries: lib,
      aliases: ali,
      nested: nes,
      brokenAliases: broken,
    };
  } catch (_) {}

  // 3. Index ALL remaining Unicorn surfaces in backend/* and src/**/*
  const extraSurfaces = [
    { dir: path.join(APP_ROOT, 'backend', 'lib'), label: 'backend/lib' },
    { dir: path.join(APP_ROOT, 'backend', 'routes'), label: 'backend/routes' },
    { dir: path.join(APP_ROOT, 'backend', 'middleware'), label: 'backend/middleware' },
    { dir: path.join(APP_ROOT, 'backend', 'integration'), label: 'backend/integration' },
    { dir: path.join(APP_ROOT, 'backend', 'constants'), label: 'backend/constants' },
    { dir: path.join(APP_ROOT, 'src', 'commerce'), label: 'src/commerce' },
    { dir: path.join(APP_ROOT, 'src', 'modules'), label: 'src/modules' },
    { dir: path.join(APP_ROOT, 'src', 'site'), label: 'src/site' },
    { dir: path.join(APP_ROOT, 'src', 'engine'), label: 'src/engine' },
    { dir: path.join(APP_ROOT, 'src', 'innovation'), label: 'src/innovation' },
    { dir: path.join(APP_ROOT, 'src', 'security'), label: 'src/security' },
    { dir: path.join(APP_ROOT, 'src', 'perf'), label: 'src/perf' },
    { dir: path.join(APP_ROOT, 'src', 'seo'), label: 'src/seo' },
    { dir: path.join(APP_ROOT, 'src', 'monitoring'), label: 'src/monitoring' },
    { dir: path.join(APP_ROOT, 'src', 'lib'), label: 'src/lib' },
    { dir: path.join(APP_ROOT, 'src', 'lightning'), label: 'src/lightning' },
    { dir: path.join(APP_ROOT, 'src', 'wasm'), label: 'src/wasm' },
    { dir: path.join(APP_ROOT, 'src', 'config'), label: 'src/config' },
    { dir: path.join(APP_ROOT, 'src', 'openapi'), label: 'src/openapi' },
  ];

  const surfaceCounts = { 'backend/modules': mcovSummary.files };
  let srcTotal = 0;
  let backendExtraTotal = 0;

  for (const s of extraSurfaces) {
    const files = walkJsFiles(s.dir, '', []);
    surfaceCounts[s.label] = files.length;
    if (s.label.startsWith('src/')) srcTotal += files.length;
    else backendExtraTotal += files.length;
    for (const f of files) {
      const baseName = f.rel.replace(/\.js$/i, '');
      entries.push({
        id: `${s.label}/${f.rel}`,
        name: baseName,
        surface: s.label,
        kind: 'platform_module',
        signal: null,
        hasManifest: false,
        manifestName: null,
        organ: classifyOrgan(f.rel, s.label),
      });
    }
  }

  // 4. Aggregate counts by AOSO Organ
  const organOrder = [
    'growth_acquisition',
    'cro_conversion',
    'fulfillment_quality',
    'redteam_security',
    'sre_performance',
    'git_native_evolution',
    'core_infrastructure',
  ];
  const byOrgan = {};
  for (const org of organOrder) {
    byOrgan[org] = { count: 0, runtimeCount: 0, sample: [] };
  }
  for (const e of entries) {
    const bucket = byOrgan[e.organ] || byOrgan.core_infrastructure;
    bucket.count += 1;
    if (e.kind === 'runtime' || e.kind === 'platform_module') bucket.runtimeCount += 1;
    if (bucket.sample.length < 8) bucket.sample.push(e.name);
  }

  const iakLive = readIakLiveSummary();

  _cache = {
    protocol: PROTOCOL,
    generatedAt: new Date().toISOString(),
    totals: {
      totalModulesIndexed: entries.length,
      backendModulesFiles: mcovSummary.files,
      backendSupportFiles: backendExtraTotal,
      srcPlatformFiles: srcTotal,
      manifestModules: manifestMap.size,
      mcovRuntimeCandidates: mcovSummary.runtime,
      mcovLibraries: mcovSummary.libraries,
      mcovAliases: mcovSummary.aliases,
      brokenAliases: mcovSummary.brokenAliases,
      coveragePct: entries.length > 0 ? 100 : 0,
    },
    iakLive,
    surfaceCounts,
    byOrgan,
    manifestList: Array.from(manifestMap.values()),
    entries,
  };
  _cacheAt = now;
  return _cache;
}

function getUniversalAtlas({ includeEntries = false } = {}) {
  const atlas = buildAtlas();
  const out = {
    ok: true,
    protocol: atlas.protocol,
    generatedAt: atlas.generatedAt,
    inventsMetrics: false,
    totals: atlas.totals,
    iakLive: atlas.iakLive,
    surfaceCounts: atlas.surfaceCounts,
    byOrgan: atlas.byOrgan,
    manifestModules: atlas.manifestList,
  };
  if (includeEntries) out.entries = atlas.entries;
  return out;
}

function searchModules(query = '', { organ = '', surface = '', limit = 25 } = {}) {
  const atlas = buildAtlas();
  const q = String(query || '').trim().toLowerCase();
  const orgFilter = String(organ || '').trim().toLowerCase();
  const surfFilter = String(surface || '').trim().toLowerCase();
  const cap = Math.max(1, Math.min(100, Number(limit) || 25));

  const matches = atlas.entries.filter((e) => {
    if (orgFilter && e.organ !== orgFilter) return false;
    if (surfFilter && !e.surface.toLowerCase().includes(surfFilter)) return false;
    if (!q) return true;
    return e.name.toLowerCase().includes(q)
      || e.id.toLowerCase().includes(q)
      || e.organ.toLowerCase().includes(q);
  });

  return {
    ok: true,
    protocol: PROTOCOL,
    query: q,
    organ: orgFilter || null,
    surface: surfFilter || null,
    totalModulesInFleet: atlas.totals.totalModulesIndexed,
    totalMatches: matches.length,
    returned: Math.min(cap, matches.length),
    modules: matches.slice(0, cap),
  };
}

function inspectModule(nameOrPath) {
  const atlas = buildAtlas();
  const target = String(nameOrPath || '').trim().toLowerCase();
  if (!target) return { ok: false, error: 'module_name_required' };
  const exact = atlas.entries.find((e) => e.name.toLowerCase() === target || e.id.toLowerCase() === target)
    || atlas.entries.find((e) => e.name.toLowerCase().includes(target) || e.id.toLowerCase().includes(target));
  if (!exact) return { ok: false, error: 'module_not_found', totalModulesInFleet: atlas.totals.totalModulesIndexed };
  return {
    ok: true,
    protocol: PROTOCOL,
    module: exact,
    totalModulesInFleet: atlas.totals.totalModulesIndexed,
  };
}

function clearCache() {
  _cache = null;
  _cacheAt = 0;
}

