'use strict';

/**
 * Module Coverage Ledger — MCOV/1.0
 *
 * Static disposition for every backend/modules JavaScript file.
 * No require() on this path. The Integrated Autonomy Kernel uses the
 * ledger to know what exists, then probes a bounded slice of runtime
 * candidates. Libraries stay on demand. Aliases must resolve.
 */

const fs = require('fs');
const path = require('path');

const PROTOCOL = 'MCOV/1.0';
const MODULES_DIR = path.join(__dirname, '..');
const SAMPLE_BYTES = 80000;
const ALIAS_MAX_BYTES = 900;
const SKIP_DIRS = new Set(['node_modules', 'autoGenerated', '.git']);

/** Never soft-required: the kernel and this ledger would recurse. */
const PROBE_SKIP = new Set([
  'integrated-autonomy-kernel.js',
  'iak/module-discovery.js',
  'iak/module-coverage.js',
]);

const ALIAS_RE = /module\.exports\s*=\s*require\s*\(\s*['"](\.[^'"]+)['"]\s*\)/;
const STRONG_RE = /getStatus\s*[:(,{]|getMetrics\s*[:(,{]|getRevenueStatus\s*[:(,{]|exports\.start\s*=|\.start\s*=\s*(?:async\s+)?(?:function|\()|(?:^|\n)\s*(?:async\s+)?start\s*\(/;
const WEAK_RE = /heal\s*\(|\.heal\s*=|start\s*\(\s*\)/;

let _sheet = null;

function clearCache() {
  _sheet = null;
}

function walkFiles(dir, relBase, out) {
  let entries = [];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (_) {
    return out;
  }
  for (const ent of entries) {
    if (SKIP_DIRS.has(ent.name)) continue;
    const abs = path.join(dir, ent.name);
    const rel = relBase ? `${relBase}/${ent.name}` : ent.name;
    if (ent.isDirectory()) walkFiles(abs, rel, out);
    else if (ent.isFile() && ent.name.endsWith('.js')) out.push({ abs, rel });
  }
  return out;
}

function aliasResolves(fromAbs, spec) {
  const base = path.resolve(path.dirname(fromAbs), spec);
  const candidates = spec.endsWith('.js')
    ? [base, path.join(base, 'index.js')]
    : [base, `${base}.js`, path.join(base, 'index.js')];
  for (const candidate of candidates) {
    try {
      if (fs.statSync(candidate).isFile()) return true;
    } catch (_) { /* next */ }
  }
  return false;
}

function classifyFile(abs, rel) {
  let size = 0;
  let text = '';
  try {
    size = fs.statSync(abs).size;
    text = fs.readFileSync(abs, 'utf8');
  } catch (e) {
    return {
      file: rel,
      name: rel.replace(/\.js$/i, ''),
      kind: 'library',
      nested: rel.includes('/'),
      signal: null,
      aliasOf: null,
      aliasOk: null,
      readError: String(e && e.message || e).slice(0, 180),
    };
  }
  const nested = rel.includes('/');
  const name = nested ? rel.replace(/\.js$/i, '') : path.basename(rel, '.js');
  const head = text.slice(0, 1200);
  const aliasMatch = head.match(ALIAS_RE);
  if (aliasMatch && size < ALIAS_MAX_BYTES) {
    return {
      file: rel,
      abs,
      name,
      kind: 'alias',
      nested,
      signal: null,
      aliasOf: aliasMatch[1],
      aliasOk: aliasResolves(abs, aliasMatch[1]),
    };
  }
  const sample = text.slice(0, SAMPLE_BYTES);
  let signal = null;
  if (STRONG_RE.test(sample)) signal = 'strong';
  else if (WEAK_RE.test(sample)) signal = 'weak';
  return {
    file: rel,
    abs,
    name,
    kind: signal ? 'runtime' : 'library',
    nested,
    signal,
    aliasOf: null,
    aliasOk: null,
  };
}

function sheet() {
  if (_sheet) return _sheet;
  const found = walkFiles(MODULES_DIR, '', []);
  const entries = found.map((row) => classifyFile(row.abs, row.rel));
  _sheet = {
    id: PROTOCOL,
    modulesDir: MODULES_DIR,
    files: entries.length,
    entries,
  };
  return _sheet;
}

/**
 * Runtime files the kernel may soft-require, strongest signal first.
 * @param {object} [opts]
 * @param {Set<string>|string[]} [opts.extraSkip] top-level basenames or relative paths
 */
function runtimeCandidates(opts = {}) {
  const extra = opts.extraSkip instanceof Set
    ? opts.extraSkip
    : new Set(opts.extraSkip || []);
  const list = sheet().entries.filter((entry) => {
    if (entry.kind !== 'runtime') return false;
    if (PROBE_SKIP.has(entry.file)) return false;
    if (extra.has(entry.file)) return false;
    if (!entry.nested && extra.has(path.basename(entry.file))) return false;
    return true;
  });
  list.sort((a, b) => {
    if (a.signal !== b.signal) return a.signal === 'strong' ? -1 : 1;
    if (a.file < b.file) return -1;
    if (a.file > b.file) return 1;
    return 0;
  });
  return list;
}

/**
 * Counts only. Safe to attach to getStatus.
 * @param {Iterable<string>} registryNames
 * @param {Array<{file:string,error:string}>} [loadErrors]
 */
function summarize(registryNames, loadErrors) {
  const entries = sheet().entries;
  const names = registryNames instanceof Set ? registryNames : new Set(registryNames || []);
  let runtime = 0;
  let libraries = 0;
  let aliases = 0;
  let nested = 0;
  let managed = 0;
  const brokenAliases = [];
  const pending = [];
  for (const entry of entries) {
    if (entry.nested) nested += 1;
    if (entry.kind === 'alias') {
      aliases += 1;
      if (!entry.aliasOk) brokenAliases.push(entry.file);
    } else if (entry.kind === 'runtime') {
      runtime += 1;
      if (names.has(entry.name)) managed += 1;
      else pending.push(entry.name);
    } else {
      libraries += 1;
    }
  }
  const errors = Array.isArray(loadErrors) ? loadErrors.slice(0, 30) : [];
  return {
    id: PROTOCOL,
    files: entries.length,
    runtime,
    libraries,
    aliases,
    nested,
    brokenAliases,
    managed,
    pendingRuntime: runtime - managed,
    pendingSample: pending.slice(0, 8),
    loadErrors: errors,
    policy: {
      starts: 'infra allowlist and configured commerce',
      probesPerTick: 'bounded',
      healthSlice: 'at most 48 status calls',
      libraries: 'on demand, not started',
    },
  };
}

module.exports = {
  PROTOCOL,
  MODULES_DIR,
  PROBE_SKIP,
  clearCache,
  sheet,
  classifyFile,
  runtimeCandidates,
  summarize,
};
