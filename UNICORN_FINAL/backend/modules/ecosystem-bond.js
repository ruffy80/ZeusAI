'use strict';

/**
 * EBO/1.0 — Ecosystem bond.
 * Static map of backend modules from the require graph. The Integrated
 * Autonomy Kernel stays the only orchestrator. This module does not start
 * it, does not soft-require the catalog, and does not write source files.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const PROTOCOL = 'EBO/1.0';
const ROOT = path.join(__dirname, '..', '..');
const MODULES_DIR = __dirname;
const BACKEND_INDEX = path.join(__dirname, '..', 'index.js');
const SITE_INDEX = path.join(ROOT, 'src', 'index.js');
const REQUIRE_RE = /require\(\s*['"](\.[^'"]+)['"]\s*\)/g;
const PLACEHOLDER_RX = new RegExp('\\b(' + ['place' + 'holder', 'not ' + 'implemented', 'notImplemented', 'coming ' + 'soon', '\\[stub', 'mock-tx-'].join('|') + ')', 'i');
const SPEND_TYPES = new Set(['payment', 'email', 'model', 'deploy', 'external_api']);
const RESTART_LIMIT = 3;
const RESTART_WINDOW_MS = 5 * 60 * 1000;
const IAK_SHIMS = [
  'central-orchestrator',
  'unicornMeshOrchestrator',
  'unicornOrchestrator',
  'meshOrchestrator',
  'saas-orchestrator-v4',
  'recovery-orchestrator',
  'billion-scale-activation-orchestrator',
];

const audit = [];
const breakers = new Map();
const queue = [];
let mapCache = null;

function killed() {
  return process.env.AUTONOMY_KILL_SWITCH === '1' || process.env.UNICORN_AUTONOMY === 'off';
}

function _rel(file) {
  return path.relative(ROOT, file).split(path.sep).join('/');
}

function _walk(dir, out) {
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch (_) { return out; }
  for (const entry of entries) {
    if (entry.name === 'node_modules' || entry.name === 'autoGenerated' || entry.name === '.git') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) _walk(full, out);
    else if (entry.name.endsWith('.js')) out.push(full);
  }
  return out;
}

function _resolve(fromFile, spec) {
  if (!spec || spec[0] !== '.') return null;
  const base = path.resolve(path.dirname(fromFile), spec);
  const candidates = [base, base + '.js', path.join(base, 'index.js')];
  for (const candidate of candidates) {
    try {
      if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
    } catch (_) { /* skip */ }
  }
  return null;
}

function _requires(file) {
  let src = '';
  try { src = fs.readFileSync(file, 'utf8'); } catch (_) { return []; }
  const out = [];
  REQUIRE_RE.lastIndex = 0;
  let match = REQUIRE_RE.exec(src);
  while (match) {
    const resolved = _resolve(file, match[1]);
    if (resolved) out.push(resolved);
    match = REQUIRE_RE.exec(src);
  }
  return out;
}

function _reachable(seeds) {
  const seen = new Set();
  const queueFiles = seeds.filter((file) => file && fs.existsSync(file));
  while (queueFiles.length) {
    const file = queueFiles.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    for (const next of _requires(file)) {
      if (!seen.has(next)) queueFiles.push(next);
    }
  }
  return seen;
}

function _healthName(src) {
  if (/function\s+health\s*\(|health\s*[:(]/.test(src) && /exports/.test(src)) {
    if (/function\s+health\s*\(/.test(src) || /health\s*:\s*function/.test(src) || /health\s*\(\)\s*\{/.test(src)) return 'health';
  }
  if (/function\s+getStatus\s*\(|getStatus\s*[:(]/.test(src)) return 'getStatus';
  return null;
}

function _exportNames(src) {
  const block = src.match(/module\.exports\s*=\s*\{([\s\S]{0,2000}?)\n\}/);
  if (!block) return ['default'];
  const names = [];
  const re = /^\s{2}([A-Za-z0-9_]+)\s*,/gm;
  let match = re.exec(block[1]);
  while (match) {
    names.push(match[1]);
    match = re.exec(block[1]);
  }
  return names.length ? names : ['default'];
}

function buildMap() {
  const files = _walk(MODULES_DIR, []);
  const reached = _reachable([BACKEND_INDEX, SITE_INDEX]);
  const byFile = new Map();
  const depsOf = new Map();
  for (const file of files) {
    const deps = _requires(file).filter((dep) => dep.startsWith(MODULES_DIR));
    depsOf.set(file, deps);
  }
  const dependents = new Map();
  for (const [file, deps] of depsOf) {
    for (const dep of deps) {
      if (!dependents.has(dep)) dependents.set(dep, []);
      dependents.get(dep).push(path.basename(file, '.js'));
    }
  }
  const modules = files.map((file) => {
    let src = '';
    try { src = fs.readFileSync(file, 'utf8'); } catch (_) { src = ''; }
    const name = path.basename(file, '.js');
    const reachable = reached.has(file);
    const placeholder = PLACEHOLDER_RX.test(src);
    let status = 'orphaned';
    if (reachable) status = 'active';
    else if (placeholder || !/module\.exports/.test(src)) status = 'dead';
    const entrypoint = reached.has(file)
      ? (file.startsWith(path.join(ROOT, 'src')) ? 'src/index.js' : 'backend/index.js')
      : null;
    const row = {
      name,
      type: src.includes("module.exports = require(") ? 'shim' : 'module',
      path: _rel(file),
      entrypoint,
      dependencies: (depsOf.get(file) || []).map((dep) => path.basename(dep, '.js')),
      dependents: dependents.get(file) || [],
      status,
      health_check: _healthName(src),
      capabilities: [name],
      inputs: _exportNames(src),
      outputs: _exportNames(src),
      placeholder,
      executed: false,
    };
    byFile.set(file, row);
    return row;
  });
  const counts = { active: 0, orphaned: 0, dead: 0, shims: 0 };
  for (const row of modules) {
    counts[row.status] += 1;
    if (row.type === 'shim') counts.shims += 1;
  }
  const map = {
    protocol: PROTOCOL,
    generatedAt: new Date().toISOString(),
    inventsModules: false,
    executedModules: false,
    orchestrator: {
      name: 'integrated-autonomy-kernel',
      id: 'IAK/1.1',
      shims: IAK_SHIMS,
      note: 'Shims re-export the kernel. They are not a second orchestrator.',
    },
    counts,
    modules,
  };
  mapCache = map;
  return map;
}

function map() {
  return mapCache || buildMap();
}

function summary() {
  const full = map();
  return {
    ok: true,
    protocol: PROTOCOL,
    inventsModules: false,
    executedModules: false,
    generatedAt: full.generatedAt,
    counts: full.counts,
    orchestrator: full.orchestrator,
    killSwitch: killed(),
    audit: audit.slice(-20),
    queueDepth: queue.length,
  };
}

function renderMarkdown(full) {
  const data = full || map();
  const orphans = data.modules.filter((row) => row.status === 'orphaned').slice(0, 12);
  const lines = [
    '# System map',
    '',
    'Static require graph of `backend/modules`. Nothing in this file was started to produce it.',
    '',
    'The only orchestrator is Integrated Autonomy Kernel `IAK/1.1`. The names ' + IAK_SHIMS.join(', ') + ' are shims.',
    '',
    '| Status | Count |',
    '|---|---|',
    '| active | ' + data.counts.active + ' |',
    '| orphaned | ' + data.counts.orphaned + ' |',
    '| dead | ' + data.counts.dead + ' |',
    '',
    '```mermaid',
    'flowchart LR',
    '  backend["backend/index.js"] --> iak["IAK/1.1"]',
    '  site["src/index.js"] --> iak',
    '  iak --> census["module-census-os"]',
    '  iak --> queue["tenant-queue"]',
    '  iak --> guardian["guardian-engines"]',
    '  iak --> sense["external-sense"]',
    '  orphans["orphaned files: ' + data.counts.orphaned + '"]:::gap',
    '  classDef gap stroke-dasharray: 5 5',
    '```',
    '',
    'Orphaned means the file is not reachable by a static `require` from `backend/index.js` or `src/index.js`. IAK can soft-require some of them later. This map does not call that scan, because the scan executes modules.',
    '',
    'Sample of orphaned files:',
    '',
  ];
  for (const row of orphans) lines.push('- `' + row.path + '`');
  lines.push('');
  return lines.join('\n');
}

function writeArtifacts() {
  const full = buildMap();
  const jsonPath = path.join(ROOT, 'SYSTEM_MAP.json');
  const mdPath = path.join(ROOT, 'SYSTEM_MAP.md');
  fs.writeFileSync(jsonPath, JSON.stringify(full));
  fs.writeFileSync(mdPath, renderMarkdown(full));
  return { ok: true, jsonPath, mdPath, counts: full.counts };
}

function envelope(partial) {
  const src = partial || {};
  return {
    id: src.id || ('env_' + crypto.randomBytes(8).toString('hex')),
    type: String(src.type || ''),
    payload: src.payload == null ? null : src.payload,
    priority: Number(src.priority) || 1,
    deadline: src.deadline || null,
    parent_task: src.parent_task || null,
    expected_schema: src.expected_schema || null,
    permissions: Array.isArray(src.permissions) ? src.permissions.slice() : [],
    cost_budget: Number(src.cost_budget) || 0,
  };
}

function _matches(value, schema) {
  if (!schema || typeof schema !== 'object') return true;
  if (!value || typeof value !== 'object') return false;
  return Object.keys(schema).every((key) => typeof value[key] === schema[key]);
}

function _audit(row) {
  const entry = Object.assign({ at: new Date().toISOString(), protocol: PROTOCOL }, row);
  audit.push(entry);
  if (audit.length > 200) audit.shift();
  return entry;
}

function noteFailure(name) {
  const now = Date.now();
  const row = breakers.get(name) || { times: [], open: false };
  row.times = row.times.filter((stamp) => now - stamp < RESTART_WINDOW_MS);
  row.times.push(now);
  row.open = row.times.length >= RESTART_LIMIT;
  breakers.set(name, row);
  return { open: row.open, attempts: row.times.length, limit: RESTART_LIMIT };
}

function dispatch(partial, handlers) {
  const task = envelope(partial);
  if (killed()) {
    return _audit({ ok: false, blocked: true, reason: 'kill_switch', task: task.id, type: task.type });
  }
  if (SPEND_TYPES.has(task.type) && task.permissions.indexOf(task.type) < 0) {
    return _audit({ ok: false, blocked: true, reason: 'permission_denied', task: task.id, type: task.type });
  }
  const table = handlers || {};
  const fn = table[task.type];
  if (typeof fn !== 'function') {
    queue.push(task);
    return _audit({ ok: false, queued: true, reason: 'no_handler', task: task.id, type: task.type });
  }
  const breaker = breakers.get(task.type);
  if (breaker && breaker.open) {
    return _audit({ ok: false, degraded: true, reason: 'circuit_open', task: task.id, type: task.type });
  }
  let last = null;
  for (let attempt = 1; attempt <= RESTART_LIMIT; attempt++) {
    try {
      const result = fn(task, attempt);
      if (!_matches(result, task.expected_schema)) {
        last = { ok: false, reason: 'schema_mismatch', attempt };
        noteFailure(task.type);
        continue;
      }
      return _audit({ ok: true, task: task.id, type: task.type, attempt, result });
    } catch (err) {
      last = { ok: false, reason: err && err.message, attempt };
      const state = noteFailure(task.type);
      if (err && err.code === 'provider_down' && typeof table[task.type + ':fallback'] === 'function') {
        try {
          const result = table[task.type + ':fallback'](task, attempt);
          if (_matches(result, task.expected_schema)) {
            return _audit({ ok: true, task: task.id, type: task.type, attempt, fallback: true, result });
          }
        } catch (fallbackErr) {
          last = { ok: false, reason: fallbackErr && fallbackErr.message, attempt };
        }
      }
      if (state.open) break;
    }
  }
  return _audit({
    ok: false,
    escalated: true,
    task: task.id,
    type: task.type,
    reason: last && last.reason,
    attempts: RESTART_LIMIT,
  });
}

function healthOf(mod) {
  const started = Date.now();
  if (!mod) {
    return { status: 'not_loaded', latency_ms: 0, last_error: null, deps_ok: null };
  }
  try {
    const body = typeof mod.health === 'function' ? mod.health() : (typeof mod.getStatus === 'function' ? mod.getStatus() : null);
    return {
      status: body && body.ok === false ? 'degraded' : 'ok',
      latency_ms: Date.now() - started,
      last_error: body && body.error ? String(body.error) : null,
      deps_ok: true,
    };
  } catch (err) {
    return {
      status: 'down',
      latency_ms: Date.now() - started,
      last_error: err && err.message,
      deps_ok: false,
    };
  }
}

function propose(full) {
  const data = full || map();
  const slow = data.modules.find((row) => row.status === 'orphaned') || data.modules[0];
  return {
    ok: true,
    protocol: PROTOCOL,
    inventsDeploys: false,
    applied: false,
    requiresHuman: true,
    rollback: 'No file was changed. Discard the proposal.',
    metric: 'orphaned count on the next static map',
    proposals: [
      {
        id: 'orphan-review',
        kind: 'dead_code',
        target: slow ? slow.path : null,
        reason: data.counts.orphaned + ' module files are outside the static require graph',
        autoApproved: false,
      },
    ],
  };
}

function drain(handlers) {
  const pending = queue.splice(0, queue.length);
  return pending.map((task) => dispatch(task, handlers));
}

function resetForTests() {
  audit.length = 0;
  queue.length = 0;
  breakers.clear();
  mapCache = null;
  delete process.env.AUTONOMY_KILL_SWITCH;
  delete process.env.UNICORN_AUTONOMY;
}

function attach(kernel) {
  if (!kernel || typeof kernel.register !== 'function') return { ok: false, reason: 'no_kernel' };
  return kernel.register('ecosystem-bond', module.exports, {
    capability: 'ecosystem-map',
    statusFn: 'summary',
  });
}

