'use strict';

/**
 * Module Census OS — MCO/1.0
 *
 * Every file under backend/modules and every name in MODULE_REGISTRY
 * gets the same sheet. A registry name with no file is absent. Five names
 * are refused: completing them would claim a capability this process does
 * not run. Alias files bind a registry name to an existing implementation.
 *
 * inventsModules and inventsRoles stay false. Effect labels come from the
 * file name, not from executing the module.
 */

const fs = require('fs');
const path = require('path');

const PROTOCOL = 'MCO/1.0';
const MODULES_DIR = __dirname;
const INDEX_FILE = path.join(__dirname, '..', 'index.js');
const SKIP_DIRS = new Set(['node_modules', 'autoGenerated', '.git']);
const PLACEHOLDER_RX = /\b(placeholder|not implemented|notImplemented|coming soon|TODO|FIXME|\[stub|mock-tx-)/i;

const REFUSED = [
  { id: 'AutonomousSpaceComputing', reason: 'No space-computing runtime exists in this process.' },
  { id: 'DecentralizedDigitalTwinNetwork', reason: 'No decentralized twin network exists in this process.' },
  { id: 'NeuralInterfaceAPI', reason: 'No neural-interface device runtime exists in this process.' },
  { id: 'QuantumInternetProtocol', reason: 'No quantum-network stack exists in this process.' },
  { id: 'QuantumMachineLearningCore', reason: 'No quantum-learning runtime exists in this process.' },
];

let _cache = null;
let _cacheAt = 0;

function clearCache() {
  _cache = null;
  _cacheAt = 0;
}

function _walk(dir, out) {
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch (_) { return out; }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) _walk(full, out);
    else if (entry.name.endsWith('.js')) out.push(full);
  }
  return out;
}

function _effect(name) {
  const s = String(name || '').toLowerCase();
  if (/pay|checkout|btc|invoice|billing|revenue|wealth|money/.test(s)) return 'settlement';
  if (/fulfill|deliver|provision|license|entitlement/.test(s)) return 'delivery';
  if (/heal|health|watchdog|slo|circuit|uptime|shield|monitor|sanity/.test(s)) return 'health';
  if (/ai|model|uaic|usi-|llm|router/.test(s)) return 'model';
  return 'organ';
}

function _parseRegistry(src) {
  const start = src.indexOf('const MODULE_REGISTRY = {');
  const end = src.indexOf('function getModuleRegistryStatus');
  const body = start >= 0 && end > start ? src.slice(start, end) : '';
  const categories = {};
  const re = /\n {2}([A-Za-z0-9_]+):\s*\[([\s\S]*?)\n {2}\],/g;
  let match = re.exec(body);
  while (match) {
    categories[match[1]] = [...match[2].matchAll(/'([^']+)'/g)].map((m) => m[1]);
    match = re.exec(body);
  }
  const adaptiveN = Number((body.match(/UNICORN_ADAPTIVE_COUNT \|\| '(\d+)'/) || [])[1] || 82);
  const engineN = Number((body.match(/UNICORN_ENGINE_COUNT \|\| '(\d+)'/) || [])[1] || 62);
  return { categories, adaptiveN, engineN };
}

function _classifyFile(full) {
  let src = '';
  try { src = fs.readFileSync(full, 'utf8'); } catch (_) { src = ''; }
  const rel = path.relative(MODULES_DIR, full).split(path.sep).join('/');
  const base = path.basename(full, '.js');
  const alias = src.match(/module\.exports\s*=\s*require\(\s*['"](\.[^'"]+)['"]\s*\)/);
  const ownership = (src.match(/OWNERSHIP: Acest fișier/g) || []).length;
  return {
    id: base,
    path: rel,
    kind: alias ? 'alias' : 'file',
    aliasOf: alias ? alias[1] : null,
    hasExports: /module\.exports|export\s+(default|const|function|class)/.test(src),
    bytes: src.length,
    placeholder: PLACEHOLDER_RX.test(src),
    duplicateOwnership: ownership > 1,
    effect: _effect(base),
    effectSource: 'name',
  };
}

function _build() {
  const indexSrc = fs.readFileSync(INDEX_FILE, 'utf8');
  const registry = _parseRegistry(indexSrc);
  const files = _walk(MODULES_DIR, []).map(_classifyFile);
  const byBase = new Map();
  for (const row of files) {
    if (!byBase.has(row.id)) byBase.set(row.id, []);
    byBase.get(row.id).push(row);
  }
  const nameCategory = new Map();
  for (const [cat, names] of Object.entries(registry.categories)) {
    for (const name of names) {
      if (!nameCategory.has(name)) nameCategory.set(name, cat);
    }
  }
  const modules = files.map((row) => ({
    ...row,
    category: nameCategory.get(row.id) || null,
    registered: nameCategory.has(row.id),
  }));
  const virtual = [];
  for (let i = 1; i <= registry.adaptiveN; i++) {
    const id = 'AdaptivePool#' + String(i).padStart(2, '0');
    virtual.push({
      id,
      path: 'adaptiveEnginePool.js',
      kind: 'virtual',
      category: 'dynamic',
      registered: true,
      hasExports: true,
      effect: 'organ',
      effectSource: 'name',
      aliasOf: './adaptiveEnginePool',
    });
  }
  for (let i = 1; i <= registry.engineN; i++) {
    const id = 'EnginePool#' + i;
    virtual.push({
      id,
      path: 'adaptiveEnginePool.js',
      kind: 'virtual',
      category: 'engines',
      registered: true,
      hasExports: true,
      effect: 'organ',
      effectSource: 'name',
      aliasOf: './adaptiveEnginePool',
    });
  }
  const refusedIds = new Set(REFUSED.map((r) => r.id));
  const absent = [];
  const refused = [];
  for (const [id, category] of nameCategory) {
    if (byBase.has(id)) continue;
    if (refusedIds.has(id)) {
      const why = REFUSED.find((r) => r.id === id);
      refused.push({
        id,
        path: null,
        kind: 'refused',
        category,
        registered: true,
        hasExports: false,
        effect: _effect(id),
        effectSource: 'name',
        reason: why.reason,
      });
      continue;
    }
    absent.push({
      id,
      path: null,
      kind: 'absent',
      category,
      registered: true,
      hasExports: false,
      effect: _effect(id),
      effectSource: 'name',
      reason: 'Registry name has no file.',
    });
  }
  const all = modules.concat(virtual, refused, absent);
  return {
    ok: true,
    protocol: PROTOCOL,
    name: 'module-census-os',
    inventsModules: false,
    inventsRoles: false,
    files: files.length,
    registeredNames: nameCategory.size,
    virtualWorkers: virtual.length,
    aliases: files.filter((r) => r.kind === 'alias').length,
    unregisteredFiles: modules.filter((r) => !r.registered).length,
    absent: absent.length,
    refused: refused.length,
    placeholders: files.filter((r) => r.placeholder).length,
    duplicateOwnership: files.filter((r) => r.duplicateOwnership).length,
    refusedNames: REFUSED.map((r) => r.id),
    note: 'Every backend module file is listed. Effect is inferred from the name. Refused names stay unpublished as code because a file would claim a capability this process does not run.',
    modules: all,
    generatedAt: new Date().toISOString(),
  };
}

function discovery() {
  if (_cache && (Date.now() - _cacheAt) < 5000) return _cache;
  _cache = _build();
  _cacheAt = Date.now();
  return _cache;
}

function find(id) {
  const needle = String(id || '');
  return discovery().modules.find((row) => row.id === needle) || null;
}

function summary() {
  const d = discovery();
  return {
    ok: d.ok,
    protocol: d.protocol,
    inventsModules: false,
    inventsRoles: false,
    files: d.files,
    registeredNames: d.registeredNames,
    virtualWorkers: d.virtualWorkers,
    aliases: d.aliases,
    unregisteredFiles: d.unregisteredFiles,
    absent: d.absent,
    refused: d.refused,
    placeholders: d.placeholders,
    duplicateOwnership: d.duplicateOwnership,
    refusedNames: d.refusedNames,
    generatedAt: d.generatedAt,
  };
}

module.exports = {
  PROTOCOL,
  REFUSED,
  clearCache,
  discovery,
  summary,
  find,
};
