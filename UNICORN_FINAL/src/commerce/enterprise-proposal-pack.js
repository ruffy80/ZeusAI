function buildPaymentSchedule(ctx) {
  const acv = Number((ctx.acv && (ctx.acv.accepted || ctx.acv.mid)) || 0);
  const kick = Number(ctx.kickoffUsd) || 0;
  const remainder = Math.max(0, acv - kick);
  const m1 = Math.round(remainder * 0.30);
  const m2 = Math.round(remainder * 0.40);
  const m3 = Math.max(0, remainder - m1 - m2);
  return `# Payment Schedule — Schedule F

**Pack ID:** ${ctx.packId}  
**Currency:** USD (BTC accepted)  
**ACV (annual):** ${_fmt(acv)}  
**Term:** ${ctx.termYears || 1} year(s)

## Schedule
| Event | Amount | Due |
|-------|--------|-----|
| Kickoff fee (engagement) | ${_fmt(kick)} | On commercial acceptance (unlocks pack) |
| Milestone M1 — Discovery / Architecture | ${_fmt(m1)} | On M1 acceptance |
| Milestone M2 — Integration ready | ${_fmt(m2)} | On M2 acceptance |
| Milestone M3 — Go-live | ${_fmt(m3)} | On go-live |
| Renewal | ${_fmt(acv)} / year | 30 days before term end |

## Notes
- Kickoff is credited toward ACV; it is non-refundable once the proposal pack is delivered.
- BTC invoices use deal-desk spot rate at mint time.
- Failure to pay within 15 days of due date may suspend non-critical work (MSA §5).

## Settlement Rails
- Bitcoin (primary sovereign rail) → ${OWNER.btc}
- PayPal / card / NOWPayments when armed on checkout
- Wire transfer on request for ACV ≥ $100,000

---
*Payment Schedule — ZeusAI AEDO*
`;
}

/**
 * @param {object} input
 * @returns {{ packId, issuedAt, documents, summary, index }}
 */
function generatePack(input) {
  const ctx = Object.assign({
    packId: 'pack_' + crypto.randomBytes(6).toString('hex'),
    issuedAt: new Date().toISOString(),
    termYears: 1,
    timelineWeeks: 12,
    kickoffUsd: 2500,
    buyer: {},
    product: {},
    requirements: {},
    acv: {},
  }, input || {});

  const docs = [
    _writeDoc(ctx.packId, 'msa', buildMsa(ctx)),
    _writeDoc(ctx.packId, 'sow', buildSow(ctx)),
    _writeDoc(ctx.packId, 'technical-appendix', buildTechAppendix(ctx)),
    _writeDoc(ctx.packId, 'security-compliance', buildSecurityPack(ctx)),
    _writeDoc(ctx.packId, 'timeline-milestones', buildTimeline(ctx)),
    _writeDoc(ctx.packId, 'payment-schedule', buildPaymentSchedule(ctx)),
  ];

  const index = {
    protocol: PROTOCOL,
    packId: ctx.packId,
    dealId: ctx.dealId || null,
    issuedAt: ctx.issuedAt,
    buyerEmail: ctx.buyer && ctx.buyer.email,
    productId: ctx.product && ctx.product.id,
    acvUsd: (ctx.acv && (ctx.acv.accepted || ctx.acv.mid)) || 0,
    kickoffUsd: ctx.kickoffUsd,
    documents: docs.map((d) => ({
      key: d.name,
      title: d.name.replace(/-/g, ' ').toUpperCase(),
      file: d.file,
      href: '/api/enterprise/pack/' + ctx.packId + '/' + d.name,
    })),
  };

  _ensure();
  fs.writeFileSync(path.join(PACK_DIR, ctx.packId + '-index.json'), JSON.stringify(index, null, 2));
  try {
    fs.appendFileSync(LOG, JSON.stringify(Object.assign({ ts: new Date().toISOString() }, index)) + '\n');
  } catch (_) {}

  return {
    packId: ctx.packId,
    issuedAt: ctx.issuedAt,
    documents: index.documents,
    summary: {
      msa: true,
      sow: true,
      technicalAppendix: true,
      securityCompliance: true,
      timelineMilestones: true,
      paymentSchedule: true,
    },
    index,
  };
}

function getPack(packId) {
  const id = String(packId || '');
  const idxPath = path.join(PACK_DIR, id + '-index.json');
  if (!fs.existsSync(idxPath)) return null;
  try { return JSON.parse(fs.readFileSync(idxPath, 'utf8')); } catch (_) { return null; }
}

function readDocument(packId, name) {
  const file = path.join(PACK_DIR, String(packId) + '-' + String(name) + '.md');
  if (!fs.existsSync(file)) return null;
  return fs.readFileSync(file, 'utf8');
}

