/**
 * Enterprise Proposal Pack Generator (EPP/1.0)
 * --------------------------------------------
 * Produces the six enterprise-grade artifacts after kickoff commitment:
 *   1. MSA  2. SOW  3. Technical Appendix  4. Security & Compliance Pack
 *   5. Timeline & Milestones  6. Payment Schedule
 *
 * Documents are structured markdown, persisted under data/commerce/proposal-packs/,
 * and cross-linked by packId / dealId.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const PROTOCOL = 'EPP/1.0';
const DATA_DIR = process.env.UNICORN_COMMERCE_DIR
  || path.join(__dirname, '..', '..', 'data', 'commerce');
const PACK_DIR = path.join(DATA_DIR, 'proposal-packs');
const LOG = path.join(DATA_DIR, 'proposal-packs.jsonl');

const OWNER = {
  legalName: process.env.LEGAL_OWNER_NAME || 'Vladoi Ionut',
  brand: 'ZeusAI / Unicorn Platform',
  email: process.env.OWNER_EMAIL || process.env.ZEUS_OWNER_EMAIL || 'vladoi_ionut@yahoo.com',
  btc: process.env.LEGAL_OWNER_BTC || process.env.BTC_WALLET_ADDRESS
    || 'bc1q4f7e66z87mdfj56kz0dj5hvcnpmh0qh4wuv22e',
  jurisdiction: process.env.LEGAL_JURISDICTION || 'Romania / EU',
};

function _ensure() {
  try { fs.mkdirSync(PACK_DIR, { recursive: true }); } catch (_) {}
}

function _fmt(n) {
  return '$' + (Number(n) || 0).toLocaleString('en-US', { maximumFractionDigits: 0 });
}

function _esc(s) {
  return String(s == null ? '' : s);
}

function _writeDoc(packId, name, body) {
  _ensure();
  const file = path.join(PACK_DIR, packId + '-' + name + '.md');
  fs.writeFileSync(file, body, 'utf8');
  return { name, file: path.basename(file), bytes: Buffer.byteLength(body) };
}

