'use strict';

/**
 * module-coverage-os.test.js — MCOV/1.0
 * Every backend module file has a disposition. The kernel probes a
 * bounded slice and does not call getStatus on the whole tree per tick.
 */

process.env.NODE_ENV = 'test';
process.env.DB_PATH = ':memory:';
process.env.DISABLE_SELF_MUTATION = '1';
process.env.JWT_SECRET = 'test-jwt-secret-for-ci-only';
process.env.UNICORN_RUNTIME_PROFILE = 'stable';
process.env.IAK_HARMONIC_MS = '60000';

const assert = require('assert');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const MODULES = path.join(ROOT, 'backend', 'modules');
const SKIP_DIRS = new Set(['node_modules', 'autoGenerated', '.git']);

let passed = 0;
function check(name, fn) {
  fn();
  passed += 1;
  console.log('  ✓', name);
}

function walk(dir) {
  let count = 0;
  let entries = [];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (_) {
    return 0;
  }
  for (const ent of entries) {
    if (SKIP_DIRS.has(ent.name)) continue;
    const abs = path.join(dir, ent.name);
    if (ent.isDirectory()) count += walk(abs);
    else if (ent.isFile() && ent.name.endsWith('.js')) count += 1;
  }
  return count;
}

console.log('Module Coverage Ledger (MCOV/1.0)');

const coverage = require('../backend/modules/iak/module-coverage');
coverage.clearCache();
const ledger = coverage.sheet();

check('sheet matches a full walk and kinds add up', () => {
  const walked = walk(MODULES);
  assert.ok(walked >= 692, `expected >=692 files, got ${walked}`);
  assert.strictEqual(ledger.files, walked);
  assert.strictEqual(ledger.id, 'MCOV/1.0');
  const kinds = { alias: 0, runtime: 0, library: 0 };
  for (const entry of ledger.entries) kinds[entry.kind] += 1;
  assert.strictEqual(kinds.alias + kinds.runtime + kinds.library, ledger.files);
});

check('aliases resolve and runtime includes nested files', () => {
  const summary = coverage.summarize([]);
  assert.strictEqual(summary.brokenAliases.length, 0);
  assert.ok(summary.aliases > 0);
  assert.ok(ledger.entries.some((entry) => entry.name === 'traffic-engine' && entry.kind === 'runtime'));
  const nestedRuntime = ledger.entries.filter((entry) => entry.kind === 'runtime' && entry.nested);
  assert.ok(nestedRuntime.length > 0);
  assert.ok(nestedRuntime.every((entry) => entry.name.includes('/')));
  assert.strictEqual(summary.runtime + summary.libraries + summary.aliases, summary.files);
  assert.strictEqual(summary.pendingRuntime, summary.runtime);
  assert.strictEqual(summary.policy.libraries, 'on demand, not started');
  assert.strictEqual(summary.policy.probesPerTick, 'bounded');
});

check('bounded probe records load errors without throwing', () => {
  const discovery = require('../backend/modules/iak/module-discovery');
  const manifest = discovery.scan({ softRequireMissing: true, maxSoftRequires: 3 });
  assert.ok(manifest.count >= 1);
  assert.ok(manifest.softRequires <= 3);
  assert.ok(Array.isArray(discovery.loadErrors()));
  assert.ok(Array.isArray(manifest.loadErrors));
  const again = discovery.scan({ softRequireMissing: true, maxSoftRequires: 3 });
  assert.ok(again.softRequires <= 3);
  assert.notStrictEqual(again.coverageCursor, manifest.coverageCursor);
});

check('IAK status reports the same ledger', () => {
  const iak = require('../backend/modules/integrated-autonomy-kernel');
  const status = iak.getStatus();
  assert.ok(status.innovations.includes('module_coverage_ledger'));
  assert.strictEqual(status.coverage.files, ledger.files);
  assert.strictEqual(status.coverage.id, 'MCOV/1.0');
  assert.strictEqual(
    status.coverage.runtime + status.coverage.libraries + status.coverage.aliases,
    status.coverage.files,
  );
  assert.ok(status.coverage.managed >= 1);
  assert.ok(status.coverage.pendingRuntime >= 0);
  assert.strictEqual(status.coverage.policy.healthSlice, 'at most 48 status calls');
  assert.strictEqual(status.coverage.policy.starts, 'infra allowlist and configured commerce');
});

console.log(`\n✅ module-coverage-os: ${passed} tests passed`);
process.exit(0);
